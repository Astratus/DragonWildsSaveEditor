#!/usr/bin/env python3
"""Regenerate (or check) the item catalog bundled in dragonwilds_save_editor/data/catalog/.

The bundled catalog is our own compilation of game facts (item IDs, names, stack sizes,
inventory tabs, unlock names), generated by dragonwilds_save_editor.gamedata from an installed
copy of the game (read only) with the rules in dragonwilds_save_editor.catalog. Output is
deterministic (sorted keys and entries, one entry per line, UTF-8, LF, final newline):
rebuilding from the same game version gives byte-identical files, and build_info.json keeps its
date unless the data changed. No local path is written anywhere.

    python packaging/build_catalog.py --game-dir <install>           # regenerate
    python packaging/build_catalog.py                                # regenerate (detect the game)
    python packaging/build_catalog.py --check --game-dir <install>   # rebuild to a temp folder and
                                                                     # compare with the committed files
    python packaging/build_catalog.py --verify                       # no game needed: shape + counts + hashes

<install> is the game's installation folder (the one holding RSDragonwilds), its RSDragonwilds
folder or its Content/Paks folder. It is only read.
Exit codes: 0 ok, 1 --check found differences, 2 error (including a failed self-check).
"""

import argparse
import os
import shutil
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from dragonwilds_save_editor import catalog  # noqa: E402

FILES = catalog.BUNDLED_FILES + (catalog.BUILD_INFO,)


def regenerate(dest, game_dir=None, date=None, progress=None, reference_dir=None):
    """Build from the game, self-check (against the catalog in `reference_dir`, default `dest`,
    when there is one) and write the bundle to `dest`. Returns the new build info."""
    items, unlocks, info = catalog.derive_from_game(game_dir, progress)
    ref = None
    ref_dir = reference_dir or dest
    if os.path.isfile(os.path.join(ref_dir, "items.json")):
        ref = catalog.load_catalog("items", out_dir=ref_dir, bundled_dir=None), \
            catalog.load_catalog("unlock_names", out_dir=ref_dir, bundled_dir=None)
    problems = catalog.self_check(items, unlocks, info, ref)
    if problems:
        raise catalog.SelfCheckError(problems)
    os.makedirs(dest, exist_ok=True)
    return catalog.write_bundle(dest, items, unlocks, info, built_date=date)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--game-dir", metavar="FOLDER", help="the game's installation folder (default: detect it)")
    ap.add_argument("--date", metavar="YYYY-MM-DD", help="build date to record (default: keep the "
                    "recorded date if the data is unchanged, else today)")
    ap.add_argument("--out", metavar="FOLDER", default=catalog.default_bundled_dir(),
                    help="bundle folder (default: dragonwilds_save_editor/data/catalog)")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true",
                      help="rebuild into a temp folder and compare with --out; write nothing")
    mode.add_argument("--verify", action="store_true",
                      help="only verify the files in --out (JSON, shape, counts, hashes); no game needed")
    a = ap.parse_args(argv)
    try:
        if a.verify:
            info = catalog.verify_catalog(a.out)
            print("OK %s (%s %s, built %s): %s" % (a.out, info.get("source", "?"), info.get("game_version", "?"),
                                                  info.get("built_at"), info.get("counts")))
            return 0
        if a.check:
            with tempfile.TemporaryDirectory(prefix="dwcat_check_") as tmp:
                if os.path.exists(os.path.join(a.out, catalog.BUILD_INFO)):
                    shutil.copyfile(os.path.join(a.out, catalog.BUILD_INFO), os.path.join(tmp, catalog.BUILD_INFO))
                regenerate(tmp, a.game_dir, a.date, catalog._cli_progress(), reference_dir=a.out)
                diff = []
                for name in FILES:
                    try:
                        with open(os.path.join(a.out, name), "rb") as f:
                            old = f.read()
                    except OSError:
                        old = None
                    with open(os.path.join(tmp, name), "rb") as f:
                        if f.read() != old:
                            diff.append(name)
            if diff:
                print("DIFFERENT: %s (run without --check to regenerate)" % ", ".join(diff))
                return 1
            print("Up to date: the bundled catalog matches a fresh build.")
            return 0
        info = regenerate(a.out, a.game_dir, a.date, catalog._cli_progress())
        catalog.verify_catalog(a.out)
        for name in FILES:
            print("%-18s %9d bytes" % (name, os.path.getsize(os.path.join(a.out, name))))
        print("game version %s, counts: %s" % (info.get("game_version"), info["counts"]))
        return 0
    except catalog.CatalogError as e:
        print("error: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
